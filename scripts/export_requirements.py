"""Export hash-pinned requirement files for Modal images from the workspace lockfile.

Modal's ``Image.uv_sync`` does not support uv workspaces, so images install these
exports instead (``Image.uv_pip_install(requirements=[...])``). They are generated,
committed and verified in CI, so every image installs exactly what ``uv.lock`` pins.

    uv run python scripts/export_requirements.py           # rewrite
    uv run python scripts/export_requirements.py --check   # fail when stale
"""

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/export_requirements.py from uv.lock. Do not edit.\n"
# output path -> (workspace package, dependency groups)
EXPORTS: dict[str, tuple[str, tuple[str, ...]]] = {
    "compute/requirements/engine.txt": ("ledger-rag", ()),
    "compute/requirements/engine-train.txt": ("ledger-rag", ("train",)),
    "services/voice/requirements.txt": ("ledger-voice", ()),
}


def export(package: str, groups: tuple[str, ...]) -> str:
    command = [
        "uv",
        "export",
        "--package",
        package,
        "--frozen",
        "--no-dev",
        "--no-emit-workspace",
        "--no-header",
        *[arg for group in groups for arg in ("--group", group)],
    ]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=True)
    return HEADER + result.stdout


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if any export is stale")
    args = parser.parse_args(argv)
    stale = []
    for relative, (package, groups) in EXPORTS.items():
        path = ROOT / relative
        content = export(package, groups)
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {relative}")
    if stale:
        print(
            "stale: " + ", ".join(stale) + " (run scripts/export_requirements.py)", file=sys.stderr
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
